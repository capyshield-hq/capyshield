//! Pure helpers behind the `capyshield` binary, kept in a library so `tests/` can reach them.

use capyshield_proxy::{Action, Event};
use serde_json::json;
use std::collections::BTreeMap;

/// Enforce-mode policy allowing exactly the hosts seen (deny-listed ones excluded), annotated with matching presets.
pub fn policy_from_events(events: &[Event]) -> String {
    let hosts: std::collections::BTreeSet<&str> = events
        .iter()
        .filter(|e| !e.rule_id.as_deref().is_some_and(|r| r.starts_with("disallowed_host:deny_hosts")))
        .map(|e| e.destination_host.as_str())
        .collect();
    let mut out = String::from(
        "# Generated by `capyshield watch --emit-policy` from observed traffic. Review before committing:\n\
         # hosts annotated with a preset can be replaced by `allow_presets: [name]`.\n\
         version: 1\nmode: enforce\nfail_mode: fail_closed\negress:\n  allow_hosts:",
    );
    if hosts.is_empty() {
        out += " []\n";
    }
    for h in hosts {
        let presets: Vec<&str> = capyshield_policy::PRESETS
            .iter()
            .filter(|(_, hs)| hs.iter().any(|p| capyshield_policy::host_matches(p, h)))
            .map(|(n, _)| n.as_str())
            .collect();
        let note = if presets.is_empty() {
            String::new()
        } else {
            format!(" # preset: {}", presets.join(", "))
        };
        out += &format!("\n    - \"{h}\"{note}");
    }
    out.push('\n');
    out
}

/// Blocked connections grouped by (host, port, rule): metadata only, never payloads or ENV values.
pub fn blocked_report(events: &[Event]) -> Vec<serde_json::Value> {
    let mut rows: BTreeMap<(&str, u16, &str), usize> = BTreeMap::new();
    for e in events.iter().filter(|e| e.action == Action::Blocked) {
        *rows
            .entry((&e.destination_host, e.port, e.rule_id.as_deref().unwrap_or_default()))
            .or_default() += 1;
    }
    rows.into_iter()
        .map(|((host, port, rule_id), count)| json!({ "host": host, "port": port, "rule_id": rule_id, "count": count }))
        .collect()
}
